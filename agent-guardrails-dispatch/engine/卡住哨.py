# -*- coding: utf-8 -*-
"""卡住哨 —— 「**有个窗把活交给外部工具软件了，然后再没回来**」⇒ 当场喊人。

⭐⭐ 立此哨的事故（2026-08-15 用户第一手亲证，⛔ 不是设想）：
    某项目一步**跨了 10.5 小时**。当时挂在 Photoshop 上的是一个模态框——
    「此文档包含嵌套的图层组。如果在版本低于 Photoshop CS6 的应用程序中打开，外观可能会发生变化。」
    ——**用户点掉它之后，进程才继续动**。
    ⚠️ 原归因（"另一个窗抢同一个 PS，COM 互相排队"）**已撤回**：那只有"同期确实有别的窗在用它"
      这个**共存事实**，⛔ 不构成因果；而"点掉框 → 立刻恢复"是一次**干预**，证据强得多。
      ⇒ ⛔ 抢占那条没被删（它只是未被证实、⛔ 不是被证伪），但它排第二。

⭐⭐ **⛔ 这不是 Photoshop 的事**（用户 2026-08-15 点名：「这个规则不止适用于 PS，
    同样适用于其他的工具软件」）。本哨**一个工具名都不认识**——它只读一本账
    （`_state/占用.json`），账上有什么就盯什么。⇒ Illustrator / Unity / Blender / Excel·COM /
    安装器 / 导出器 / 任何自带界面的程序，**只要项目在 `独占资源:` 里声明了，就自动被盯上**。
    ⛔ 引擎里⛔ 不许再出现第二个工具名。

⭐ 它治的那个形状，一句话：
    **从外面看，「在飞快地干活」和「弹了框干等你」长得一模一样——都是没返回。**
    ⇒ 唯一能把这两件分开的东西，是**在旁边数时间的第三方**。

⚠️⚠️ **为什么⛔ 不能用 `哨.py` 的 PostToolUse 来干这件事**（这是本哨存在的全部理由）：
    PostToolUse 在**调用返回之后**才跑。那 10.5 小时里，卡住的窗自己**一次也开不了口**
    ——它就阻塞在那个调用上。事后报一句「这步用了 630 分钟」是**马后炮**，救不回任何东西。
    ⇒ 必须有个**进程外**的东西在数，⛔ 这件事在窗内无解。

⚠️ **为什么这里用轮询、而 `守望.py` 明令「⛔ 别用闹钟，用门磁」**（⛔ 不是忘了那条纪律）：
    门磁抓的是**发生了一件事**（文件被改），有边可触发。
    本哨抓的是**一件事迟迟没发生**（登记迟迟没被交还）——**「没有事件」没有边**。
    ⇒ 轮询在这里⛔ 不是偷懒，是唯一形态。⭐ 但它守的是**一个小 json**，
      每 60 秒读一次的代价可以忽略；且**没到点就一行不输出** ⇒ 模型侧 0 成本（同守望）。

⚠️⚠️ **一条必须先说清的局限（⛔ 别把它当万能）**：
    **卡住的那个窗自己看不到这声**——它就阻塞在那儿，什么也收不到。
    ⇒ 这一声是喊给 ⭐**用户**（唯一能去点那一下的人）和**别的窗**的。
    ⇒ 所以正确跑法是二选一：① 在**另一个窗**用 `Monitor` 拉起它；
      ② ⭐ 直接在一个**自己的终端**里跑着（推荐——⛔ 不依赖任何窗还活着）。

跑法：
    python <垫片目录>/卡住哨.py                     # 用账上声明的正常时长，超 2 倍就喊
    python <垫片目录>/卡住哨.py --倍 3 --隔 30      # 更宽松/更勤快
    python <垫片目录>/卡住哨.py --账 D:/x/占用.json # 指定账本（一般不用）
"""
import argparse
import json
import os
import sys
import time
from pathlib import Path

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")

# ⭐ 找账本：与 哨.py 的 STATE_DIR 同一口径（env 优先），⛔ 别各算各的
ROOT = Path(__file__).resolve().parent.parent
默认账 = Path(os.environ.get("WORLDBOOK_STATE_DIR") or (ROOT / "_state")) / "占用.json"

# ⭐ 醒来该干什么，写进**事件那一行本身**（同守望纪律②）——⛔ 不写进任何要人记得去读的文档
醒来清单 = ("① ⭐ **先去看那个程序的界面**：有没有一个框在等人点（兼容性提示/覆盖确认/"
            "许可证过期/更新提醒）——⛔ 代码关不掉它，**只有人点那一下能解开** "
            "② 没有框 ⇒ 再问是不是**另一个窗也在用它**、两边排队 "
            "③ 都不是 ⇒ 那它可能真就是这么久，⭐ 去把 `正常时长分钟` 调对，⛔ 别让它天天误报")


def 写心跳(账路, 状态="在岗", 轮=0):
    """⭐⭐ W-5 复核 §五.2 方案 A（用户 2026-08-15 拍板）：留一份「我此刻在岗」的凭据。

    ⚠️ 立此机制的原问（复核）：「谁在什么时刻会真的去开那个终端？」——答案是**没有人**。
      因为它要求人在**每次**驱动外部程序**之前主动想起来**，而立仓事故恰恰证明人不会想起来。
    ⇒ ⭐ 有了心跳，`哨.py` 就能在**登记那一刻**（＝正要动手那一刻）看一眼，
      没心跳就贴一句「此刻没人盯着」——⛔ 不靠人记得，且⛔ 不拦他。
    ⭐ 顺带解掉复核 S1：卡住哨被 kill 之后，「一直没喊」和「早就没了」终于长得不一样了。
    """
    try:
        p = Path(账路).parent / "卡住哨心跳.json"
        p.parent.mkdir(parents=True, exist_ok=True)
        tmp = p.with_suffix(".json.tmp")
        tmp.write_text(json.dumps({"时刻": time.time(), "状态": 状态, "轮": 轮,
                                   "账": str(账路), "pid": os.getpid()},
                                  ensure_ascii=False), encoding="utf-8")
        os.replace(str(tmp), str(p))
    except Exception:
        pass      # ⛔ 写不了心跳不许拖垮守夜本身——最坏就是退回"看不见在岗"，同改前


def 读账(账):
    """返回 (账dict, 状态)。⭐ 状态三分：'好' / '没有' / '坏'。

    ⛔⛔ **「读不出来」绝不许并进「没有卡住的」**——那正是本套件反复要消灭的东西：
      沉默有两种含义。账坏了要喊，⛔ 不能当空账静静跑下去。
    """
    try:
        if not 账.is_file():
            return {}, "没有"
        d = json.loads(账.read_text(encoding="utf-8"))
        if not isinstance(d, dict) or any(not isinstance(v, dict) for v in d.values()):
            return {}, "坏"
        return d, "好"
    except Exception:
        return {}, "坏"


def 主():
    ap = argparse.ArgumentParser(description="卡住哨：有窗把活交给外部工具软件后再没回来 ⇒ 喊人")
    ap.add_argument("--账", default=str(默认账), help="占用账本路径（默认＝库的 _state/占用.json）")
    # ⚠️ 下面四个默认值的出处⛔ 逐个如实交代（本仓正在治「裸阈值」那个病，⛔ 不许我再种四颗）：
    ap.add_argument("--倍", type=float, default=2.0,
                    help="⭐ 超过「正常时长」几倍才喊。⚠️ 2 是**拍的**，⛔ 无实测依据——"
                         "取 2 的道理只是「一倍以内属正常波动」。真用起来后按误报回校")
    ap.add_argument("--隔", type=float, default=60.0,
                    help="几秒查一次账。⭐ 60 的道理：本哨要抓的是**分钟～小时**级的卡死，"
                         "⛔ 不追求秒级；读的又只是一个小 json，代价可忽略")
    ap.add_argument("--再报分钟", type=float, default=0.0,
                    help="同一条登记隔多久再喊一次。⭐ 默认 0 ＝ **按它自己的正常时长再等一轮**"
                         "（⛔ 不写死一个数——快工具该催得勤，慢工具不该被烦）")
    ap.add_argument("--上限", type=int, default=10,
                    help="⭐ 至多喊几次就自撤（⛔ 硬数）。10 沿用守望的口径，⚠️ 同样**尚未校过**")
    a = ap.parse_args()
    账路 = Path(a.账)

    # ① 布防声。⭐⭐ 这一声是**通路证明**：看到它，之后的沉默才可信；
    #    ⛔ 没看到它 ＝ 机制压根没起来，此时"一直没喊"什么都不能证明。
    账0, 状态0 = 读账(账路)
    print("🛡️ 卡住哨已布防 · 账本 %s · 每 %g 秒查一次 · 超「正常时长 × %g」就喊 · "
          "至多喊 %d 次后自撤 ⇒ ⭐ 这行是通路证明：⛔ 没有它就说明机制没起来，"
          "之后的「一直没动静」不作数" % (账路.as_posix(), a.隔, a.倍, a.上限), flush=True)
    print("ℹ️ ⚠️ **卡住的那个窗收不到本哨的声音**（它就阻塞在那儿）⇒ 这些话是喊给"
          "⭐ **你本人**（唯一能去点那一下的）和别的窗的。", flush=True)

    # ② ⭐⭐ 「关着」必须看得见（同守望「盯到 0 个文件要喊」那条实测教训）。
    #    ⛔ 空账**不是**错误——它就是"此刻没人在用外部程序"的正常样子；
    #    但如果你是**特意为某次调用**布的防，空账就说明那次调用**根本没被登记**
    #    ⇒ 这防等于白布，而白布和"平安无事"长得一模一样。
    if 状态0 == "坏":
        print("⛔⛔ 卡住哨警告 · **账本读不出来**（不是 json / 结构不对）：%s\n"
              "   ⇒ 在修好之前，本哨**什么都盯不到**，⛔ 别把接下来的安静当成「没人卡住」。"
              % 账路.as_posix(), flush=True)
    elif not 账0:
        print("⚠️ 卡住哨提醒 · **此刻账上一条登记都没有** ⇒ 现在没有东西可盯。\n"
              "   ⭐ 这**可能是对的**（没有窗在用外部工具软件时，账本本来就是空的）；\n"
              "   ⛔ 但如果你是**特意为某次调用**布的防，那就说明那次调用**没有被登记**——\n"
              "     多半是该项目 `.claude/工作流.yaml` 里**没声明 `独占资源:`**，\n"
              "     或声明了但**命令正则咬不住**你实际跑的那条命令。\n"
              "   ⇒ ⭐ 先 `python <垫片目录>/接入.py --检查 <项目>` 看一眼卫兵在不在岗，"
              "⛔ 别让它这么空转着。", flush=True)
    else:
        print("✅ 卡住哨在岗 · 账上现有 %d 条登记：%s"
              % (len(账0), "、".join("%s(%s)" % (k, (v or {}).get("项目") or "?")
                                     for k, v in list(账0.items())[:6])), flush=True)

    喊过 = 0
    上次喊 = {}          # 键 ⇒ 上次喊它的时刻
    上次状态 = 状态0
    轮 = 0
    写心跳(账路, "在岗", 轮)      # ⭐ 布防那一刻就写，⛔ 别等第一轮——否则前 60 秒是"没人在岗"
    try:
        while True:
            time.sleep(a.隔)
            轮 += 1
            写心跳(账路, "在岗", 轮)
            账, 状态 = 读账(账路)
            # ⭐ 账本状态**变化**时出声：好→坏要喊（不然它坏了你也不知道，然后一直很安静）
            if 状态 != 上次状态:
                if 状态 == "坏":
                    print("⛔⛔ 卡住哨 · **账本刚刚变得读不出来了** ⇒ 从这一刻起本哨盯不到任何东西，"
                          "⛔ 别把之后的安静当成「没人卡住」：%s" % 账路.as_posix(), flush=True)
                elif 上次状态 == "坏":
                    print("✅ 卡住哨 · 账本恢复可读，继续盯。", flush=True)
                上次状态 = 状态
            if 状态 != "好":
                continue
            now = time.time()
            # ⭐ W-5 复核 D7 配套：先记下这一轮**有哪些**够得着门槛，撤防时才说得出「还漏了谁」
            待喊, 本轮已喊 = [], set()
            for 名, 持 in 账.items():
                try:
                    _起 = float((持 or {}).get("时间") or 0)
                    _正 = float((持 or {}).get("正常分钟") or 0) or 10.0
                    if _起 > 0 and (now - _起) / 60.0 >= _正 * a.倍:
                        待喊.append(str(名))
                except (TypeError, ValueError):
                    pass
            for 名, 持 in 账.items():
                try:
                    起 = float((持 or {}).get("时间") or 0)
                    正常 = float((持 or {}).get("正常分钟") or 0)
                except (TypeError, ValueError):
                    # ⛔⛔ W-5 复核 D6：原来这里直接 continue ⇒ 那一条被**静默跳过**，
                    #   而屏幕上还写着「✅ 在岗 · N 条登记」。⭐ 「坏账要喊」这条纪律
                    #   原本只做到了「整本账」那一层，⛔ 没做到「一条记录」这一层。
                    键坏 = "坏字段|" + str(名)
                    if now - 上次喊.get(键坏, 0) >= 300:
                        上次喊[键坏] = now
                        print("⛔ 卡住哨｜**「%s」这条登记的字段是坏的**（时间／正常分钟读不成数）"
                              "⇒ ⭐ 这一条我**盯不了**，⛔ 别把它的安静当成没卡住。"
                              "账本：%s" % (名, 账路.as_posix()), flush=True)
                    continue
                if 起 <= 0:
                    continue
                if 正常 <= 0:
                    # ⚠️ 老账本（2026-08-15 之前登记的）没有这个字段 ⇒ ⛔ 不能当 0 处理
                    #    （当 0 会让它**每一轮都喊**）。退兜底，并在话里说明这个数是哪来的。
                    正常, 兜底了 = 10.0, True
                else:
                    兜底了 = str((持 or {}).get("阈值来源") or "").startswith("引擎兜底")
                久 = (now - 起) / 60.0
                门 = 正常 * a.倍
                # ⛔⛔ W-5 复核 D5：时刻在**未来**（改过系统时钟／手工编过账）⇒ 久 是负数
                #   ⇒ 永远够不到门槛 ⇒ **永远不喊，且一个字都不说**。⭐ 又是「安静有两种含义」。
                if 久 < 0:
                    键未来 = "未来|" + str(名)
                    if now - 上次喊.get(键未来, 0) >= 300:
                        上次喊[键未来] = now
                        print("⛔ 卡住哨｜**「%s」这条登记的时刻在未来**（比现在还晚 %.0f 分钟）"
                              "⇒ 账可能被改过或时钟不对。⭐ 这一条我**盯不了**，"
                              "⛔ 别信接下来的安静。" % (名, -久), flush=True)
                    continue
                if 久 < 门:
                    continue
                隔多久再喊 = a.再报分钟 if a.再报分钟 > 0 else 正常 * a.倍
                # ⛔⛔ W-5 复核 D4：原来是 "%g" ⇒ 只留 6 位有效数字 ⇒ **4.6 小时内所有登记的键都一样**
                #   ⇒ 注释里写的「换了一次新调用会重新计次」**根本不成立**。
                #   杀伤半径（复核实测）：默认参数下看不出来（再报间隔恰好等于门槛，两个错互相抵消）；
                #   ⭐ 一旦按文档用 `--再报分钟` 把间隔拉长，**一次全新的、真的卡住会被静默压掉**。
                键 = "%s|%.3f" % (名, 起)   # ⭐ 带登记时刻（毫秒级）⇒ 换了一次新调用真的会重新计次
                if now - 上次喊.get(键, 0) < 隔多久再喊 * 60:
                    continue
                上次喊[键] = now
                本轮已喊.add(str(名))
                喊过 += 1
                判据 = ("正常 %g 分钟 × %g" % (正常, a.倍)) + (
                    "（⚠️ 正常时长是**引擎兜底的拍脑袋数**，⛔ 不是这个工具真实量出来的 ⇒ "
                    "去 `独占资源:` 里补 `正常时长分钟`）" if 兜底了 else "（本项目声明）")
                # ⭐ 不足 1 分钟要说秒：实跑（2026-08-15 端到端）打出过「已经 0 分钟没有回来了」
                #   ——⛔ 一句读起来像坏了的话会让人怀疑整个哨，而不是去看那个框。
                久文 = ("%.0f 秒" % (久 * 60)) if 久 < 1 else ("%.0f 分钟" % 久)
                print("📣📣 卡住哨｜⛔ **%s 已经 %s没有回来了**（判据：%s）\n"
                      "   · 项目：%s · 占用方会话：%s\n"
                      "   · 它当时在跑：%s\n"
                      "   ⇒ %s"
                      % (名, 久文, 判据,
                         (持 or {}).get("项目") or "?", (持 or {}).get("会话") or "?",
                         str((持 or {}).get("干什么") or "")[:120], 醒来清单), flush=True)
                if 喊过 >= a.上限:
                    # ③ 撤防声（触顶）。⛔ 不自行续命——一次布防 ＝ 一次预算（同守望）。
                    # ⛔⛔ W-5 复核 D7：原来在这里**当场 return** ⇒ 15 条同时超时、上限 10
                    #   ⇒ 一轮吃光名额，剩下 5 条**一次都没被点名**就退了，而且没人说漏了谁。
                    #   ⇒ ⭐ 改成「把这一轮说完再退」，并**点名还有谁没说到**。
                    剩 = [k for k in 待喊 if k not in 本轮已喊]
                    if 剩:
                        print("⚠️ 卡住哨｜**这一轮还有 %d 条超时的没来得及点名**：%s"
                              % (len(剩), "、".join(剩[:8]) + ("…" if len(剩) > 8 else "")),
                              flush=True)
                    print("🛡️ 卡住哨撤防：已喊满 %d 次上限 ⇒ ⛔ 不自行续命。"
                          "还要盯就重新布防（⭐ 先想清楚为什么这么吵——多半是"
                          "`正常时长分钟` 定得太小；⭐ 若是多条资源同时卡，"
                          "把 --上限 调大或分开布防）" % a.上限, flush=True)
                    写心跳(账路, "撤防", 轮)
                    return 0
    except KeyboardInterrupt:
        print("🛡️ 卡住哨撤防：被叫停 · 共喊 %d 次" % 喊过, flush=True)
        写心跳(账路, "撤防", 轮)
        return 0
    except Exception as e:
        # ⭐⭐ 兜住一切意外，并且**大声说出来**（同守望：静静地死 ＝ 让沉默有两种含义）。
        import traceback
        print("⛔⛔ 卡住哨自己崩了（⛔ 不是「没人卡住」）：%s: %s · 共喊 %d 次 "
              "⇒ ⭐ 把这行当异常处理，⛔ 别当成一切太平" % (type(e).__name__, e, 喊过), flush=True)
        print("⛔ 崩溃现场：" + " | ".join(traceback.format_exc().splitlines()[-4:]), flush=True)
